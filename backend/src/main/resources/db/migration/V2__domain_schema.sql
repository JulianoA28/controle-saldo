-- Domain schema. Constraints here are the final guarantee of the business rules:
-- they also protect the legacy data load, which bypasses the application.

CREATE TABLE agency (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    varchar(20)  NOT NULL CONSTRAINT uk_agency_code UNIQUE,
    acronym varchar(20)  NOT NULL,
    name    varchar(150) NOT NULL,
    state   varchar(2)   NOT NULL CONSTRAINT ck_agency_state CHECK (state ~ '^[A-Z]{2}$')
);

CREATE TABLE item (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(20)  NOT NULL CONSTRAINT uk_item_code UNIQUE,
    description   varchar(200) NOT NULL,
    -- Units are stored normalized (trimmed, upper case): 'UN', not ' un'.
    unit          varchar(10)  NOT NULL CONSTRAINT ck_item_unit_normalized
                                 CHECK (unit <> '' AND unit = upper(btrim(unit))),
    -- R1: balance is never negative, whatever writes to this table.
    balance       integer      NOT NULL CONSTRAINT ck_item_balance_non_negative CHECK (balance >= 0),
    active        boolean      NOT NULL DEFAULT true,
    registered_on date         NOT NULL DEFAULT current_date,
    -- R5: optimistic locking for edits of descriptive fields.
    version       bigint       NOT NULL DEFAULT 0
);

-- Audit trail of manual balance adjustments (stock entries, inventory corrections).
CREATE TABLE item_balance_adjustment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       bigint       NOT NULL REFERENCES item (id),
    delta         integer      NOT NULL CONSTRAINT ck_adjustment_delta_non_zero CHECK (delta <> 0),
    balance_after integer      NOT NULL,
    reason        varchar(200) NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now()
);
-- Adjustment history of one item, newest first.
CREATE INDEX ix_item_balance_adjustment_item ON item_balance_adjustment (item_id, created_at DESC);

-- "orders" because ORDER is a reserved word.
CREATE TABLE orders (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- R6: the client-supplied idempotency key; a resend can never create a second row.
    external_id         uuid         NOT NULL CONSTRAINT uk_orders_external_id UNIQUE,
    agency_id           bigint       NOT NULL REFERENCES agency (id),
    requester           varchar(100) NOT NULL,
    origin              varchar(20)  NOT NULL CONSTRAINT ck_orders_origin CHECK (origin IN ('PORTAL', 'INTEGRATION')),
    status              varchar(20)  NOT NULL CONSTRAINT ck_orders_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    created_at          timestamptz  NOT NULL,
    cancelled_at        timestamptz,
    cancellation_reason varchar(200),
    CONSTRAINT ck_orders_cancellation_consistent CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);
-- Order list: newest first, optionally filtered by status (1M rows, always paginated).
CREATE INDEX ix_orders_created_at ON orders (created_at DESC, id DESC);
-- Order list filtered by agency, newest first.
CREATE INDEX ix_orders_agency_created_at ON orders (agency_id, created_at DESC, id DESC);

CREATE TABLE order_item (
    id       bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint  NOT NULL REFERENCES orders (id),
    item_id  bigint  NOT NULL REFERENCES item (id),
    quantity integer NOT NULL CONSTRAINT ck_order_item_quantity_positive CHECK (quantity > 0),
    -- One line per item per order; also serves "lines of an order" lookups (leading order_id).
    CONSTRAINT uk_order_item UNIQUE (order_id, item_id)
);
